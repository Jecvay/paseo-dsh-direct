import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { build } from 'esbuild'

const args = process.argv.slice(2)
if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
  throw new Error(`Unsupported build arguments: ${args.join(' ')} (expected none or --check)`)
}
const check = args[0] === '--check'

function templateLiteral(text) {
  return `\`${text
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${')
    .replace(/\r/g, '\\r')}\``
}

const result = await build({
  entryPoints: ['server/dsh/bridge.ts'],
  outfile: 'dist/dsh-bridge.mjs',
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  sourcemap: false,
  legalComments: 'none',
  write: false,
})

// esbuild reports output paths with the platform separator (backslashes on Windows).
const bridge = result.outputFiles.find(file => file.path.replace(/\\/g, '/').endsWith('/dsh-bridge.mjs'))
if (!bridge) throw new Error('esbuild did not produce dist/dsh-bridge.mjs')

// Paseo only loads plugin modules from client/, server/ and shared/, so the
// plugin version is baked in here instead of importing package.json at runtime.
const { version } = JSON.parse(await readFile('package.json', 'utf8'))
const generatedFiles = [
  [
    'server/generated-bridge.ts',
    `// Generated by npm run build; do not edit.\nexport const DSH_BRIDGE_SOURCE: string = ${templateLiteral(bridge.text)};\n`,
  ],
  [
    'server/generated-version.ts',
    `// Generated by npm run build; do not edit.\nexport const PLUGIN_VERSION = ${JSON.stringify(version)};\n`,
  ],
]

if (check) {
  const stale = []
  for (const [file, expected] of generatedFiles) {
    let actual
    try {
      actual = await readFile(file, 'utf8')
    } catch (error) {
      if (error?.code === 'ENOENT') {
        stale.push(file)
        continue
      }
      throw error
    }
    if (actual !== expected) stale.push(file)
  }
  if (stale.length > 0) {
    throw new Error(`Generated files are out of date (${stale.join(', ')}); run \`npm run build\``)
  }
} else {
  await mkdir('dist', { recursive: true })
  await writeFile('dist/dsh-bridge.mjs', bridge.contents)
  for (const [file, content] of generatedFiles) {
    await writeFile(file, content)
  }
}
