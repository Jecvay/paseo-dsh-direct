import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { build } from 'esbuild'

const result = await build({
  entryPoints: ['server/dsh/bridge.ts'],
  outfile: 'dist/dsh-bridge.mjs',
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  sourcemap: false,
  legalComments: 'none',
  write: false,
})

const bridge = result.outputFiles.find(file => file.path.endsWith('/dsh-bridge.mjs'))
if (!bridge) throw new Error('esbuild did not produce dist/dsh-bridge.mjs')
await mkdir('dist', { recursive: true })
await writeFile('dist/dsh-bridge.mjs', bridge.contents)
await writeFile(
  'server/generated-bridge.ts',
  `// Generated by npm run build; do not edit.\nexport const DSH_BRIDGE_SOURCE = ${JSON.stringify(bridge.text)};\n`,
)

// Paseo only loads plugin modules from client/, server/ and shared/, so the
// plugin version is baked in here instead of importing package.json at runtime.
const { version } = JSON.parse(await readFile('package.json', 'utf8'))
await writeFile(
  'server/generated-version.ts',
  `// Generated by npm run build; do not edit.\nexport const PLUGIN_VERSION = ${JSON.stringify(version)};\n`,
)
